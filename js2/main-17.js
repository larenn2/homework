let coefficient;
switch (true) {
  case type == "Стандарт":
    coefficient = 1;
    break;

  case type == "Экспресс":
    coefficient = 1.5;
    break;

  case type == "Премиум":
    coefficient = 2;
    break;
}
// 5. Расчёт итоговой стоимости доставки:
//    Итоговая стоимость = базовая стоимость * коэффициент.
